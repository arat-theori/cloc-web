const FALLBACK = "#666666";

const HASH_PALETTE = [
  "#a78bfa",
  "#60a5fa",
  "#34d399",
  "#fbbf24",
  "#fb7185",
  "#22d3ee",
  "#f472b6",
  "#a3e635",
  "#facc15",
  "#818cf8",
];

export function languageColor(name: string): string {
  const known = COLORS[name];
  if (known) return known;
  // Stable color from a tiny hash so unmapped languages don't all share one color.
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
  return HASH_PALETTE[h % HASH_PALETTE.length] ?? FALLBACK;
}
